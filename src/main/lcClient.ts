import { app } from 'electron'
import { mkdirSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { LC_PROTOCOL } from '../shared/lc'

/**
 * The `lc` command itself, generated at runtime rather than built.
 *
 * Same trick as the agent-hook reporter: the app writes the script into its own
 * data folder on startup. That keeps it out of the build config entirely and
 * makes dev and packaged builds behave identically, which the hook work already
 * proved out tonight.
 *
 * It runs under the app's own Electron binary in node mode, so there is nothing
 * to install and no dependency on the user having Node at all. The shell
 * integration defines the function that points at it.
 */

export function lcAssetDir(): string {
  return join(app.getPath('userData'), 'lc')
}

export function lcScriptPath(): string {
  return join(lcAssetDir(), 'lc.js')
}

/**
 * The shell function, for the generated rc files.
 *
 * Only inside Light Code's panes, which is the only place it means anything:
 * the app it talks to has to be running, and this is where that is guaranteed.
 */
export function lcShellFunction(electron: string, script: string): string {
  const q = (v: string): string => `'${v.replace(/'/g, "'\\''")}'`
  return [
    '',
    '# Light Code: the agent CLI. Runs under the app\'s own Electron in node mode,',
    '# so it needs nothing installed. Refused unless you switch it on in the app.',
    `lc() { ELECTRON_RUN_AS_NODE=1 ${q(electron)} ${q(script)} "$@"; }`
  ].join('\n')
}

/** The same, for PowerShell. */
export function lcPowerShellFunction(electron: string, script: string): string {
  const q = (v: string): string => `'${v.replace(/'/g, "''")}'`
  return (
    `function global:lc { $env:ELECTRON_RUN_AS_NODE = '1'; ` +
    `& ${q(electron)} ${q(script)} @args }`
  )
}

/**
 * The client. Plain CommonJS with nothing but node builtins, because it runs
 * outside the bundle and has to keep working when the app is upgraded under it.
 *
 * It is deliberately thin: connect, write one line, read one line, print it,
 * exit. Every decision — whether the switch is on, what a pane is doing, what
 * is allowed — belongs to the app, which is the only side that knows.
 *
 * Which app, though, is the one thing the script cannot be told at generation
 * time. It lives at one fixed path in userData that every running Light Code
 * shares, so a second launch overwrites it; a socket baked in here would send
 * the first window's panes to whichever window started last. The pane's own
 * environment is the only source that cannot be rewritten behind its back.
 */
export function lcClientScript(): string {
  return `#!/usr/bin/env node
// Generated by Light Code. Talks to the running app over a socket it owns.
// Protocol ${LC_PROTOCOL}. Regenerated on every launch — edits will not survive.
'use strict'
const net = require('net')

// Put here by the app that spawned this pane's shell, so a pane always reaches
// the window it belongs to even with several Light Codes running.
const SOCKET = process.env.LIGHTCODE_LC_SOCKET
const USAGE = [
  'lc — drive Light Code panes from a terminal',
  '',
  '  lc ls                                  every pane, with status and branch',
  '  lc read <pane> [--tail N]              recent output, oldest line first',
  '  lc send <pane> <text> [--no-enter]     type into a pane',
  '  lc close <pane>                        close a pane (worktrees are kept)',
  '  lc wait <pane...> [--for idle|exit] [--timeout-ms N]',
  '  lc fan <task> <count> <prompt> [--plan]   worktrees + agents in one call',
  '',
  '  --json    print the raw reply instead of a table',
  '',
  'Every command needs the app running with the agent CLI switched on.'
].join('\\n')

function flag(args, name) {
  const i = args.indexOf(name)
  if (i === -1) return null
  const value = args[i + 1]
  args.splice(i, value === undefined ? 1 : 2)
  return value === undefined ? '' : value
}

function has(args, name) {
  const i = args.indexOf(name)
  if (i === -1) return false
  args.splice(i, 1)
  return true
}

function build(args) {
  const json = has(args, '--json')
  const cmd = args.shift()
  if (!cmd || cmd === 'help' || cmd === '--help' || cmd === '-h') return { usage: true }

  // The app puts the pane id in the environment of every shell it spawns, so
  // the caller can be told which row is itself rather than having to work it out.
  if (cmd === 'ls') return { json, req: { cmd: 'ls', from: process.env.LIGHTCODE_PANE } }

  if (cmd === 'read') {
    const pane = args.shift()
    if (!pane) return { error: 'read needs a pane id. Try: lc ls' }
    const tail = Number(flag(args, '--tail') || 50)
    return { json, req: { cmd: 'read', pane, tail: Number.isFinite(tail) ? tail : 50 } }
  }

  if (cmd === 'send') {
    const pane = args.shift()
    const noEnter = has(args, '--no-enter')
    const text = args.join(' ')
    if (!pane || !text) return { error: 'send needs a pane id and some text.' }
    return { json, req: { cmd: 'send', pane, text, enter: !noEnter } }
  }

  if (cmd === 'close') {
    const pane = args.shift()
    if (!pane) return { error: 'close needs a pane id.' }
    return { json, req: { cmd: 'close', pane } }
  }

  if (cmd === 'wait') {
    const forWhat = flag(args, '--for') || 'idle'
    if (forWhat !== 'idle' && forWhat !== 'exit') {
      return { error: '--for takes idle or exit.' }
    }
    const timeoutMs = Number(flag(args, '--timeout-ms') || 600000)
    const panes = args.filter((a) => !a.startsWith('--'))
    if (panes.length === 0) return { error: 'wait needs at least one pane id.' }
    return {
      json,
      req: { cmd: 'wait', panes, for: forWhat, timeoutMs: Number.isFinite(timeoutMs) ? timeoutMs : 600000 }
    }
  }

  if (cmd === 'fan') {
    const plan = has(args, '--plan')
    const task = args.shift()
    const count = Number(args.shift())
    const prompt = args.join(' ')
    if (!task || !Number.isFinite(count) || !prompt) {
      return { error: 'fan needs a task name, a count, and a prompt.' }
    }
    return { json, req: { cmd: 'fan', task, count, prompt, plan, from: process.env.LIGHTCODE_PANE } }
  }

  return { error: 'Unknown command: ' + cmd + '\\n\\n' + USAGE }
}

function render(res) {
  if (res.panes) {
    if (res.panes.length === 0) return 'No panes.'
    // Silence here is the dangerous answer. The system prompt tells agents the
    // asterisk is how they identify themselves, so a listing with no asterisk
    // reads as "none of these is me, all are safe to drive". Say so out loud
    // rather than letting an absent marker be mistaken for a present one.
    const warning = res.panes.some((p) => p.self)
      ? ''
      : 'WARNING: could not identify which pane you are in, so no row is marked. ' +
        'Do not send commands to any of these without checking which is yours.\\n\\n'
    return warning + res.panes
      .map((p) => {
        const ctx = Math.round(p.contextTokens / 1000) + 'k/' + Math.round(p.contextWindow / 1000) + 'k'
        const branch = p.branch ? (p.worktree ? p.branch + ' (worktree)' : p.branch) : '-'
        const who = p.self ? '* ' : '  '
        return who + [p.pane, p.status.padEnd(8), ctx.padEnd(11), branch.padEnd(24), p.cwd].join('  ')
      })
      .join('\\n')
  }
  if (res.lines) return res.lines.join('\\n')
  if (res.done) return res.done.map((d) => d.pane + ' ' + d.state).join('\\n')
  if (res.created) return res.created.map((c) => c.pane + ' ' + c.branch).join('\\n')
  return 'ok'
}

const parsed = build(process.argv.slice(2))
if (parsed.usage) {
  console.log(USAGE)
  process.exit(0)
}
if (parsed.error) {
  console.error(parsed.error)
  process.exit(2)
}
// Refused rather than guessed at. Picking some other window's socket is how an
// agent ends up typing into panes in a repository it has never seen.
if (!SOCKET) {
  console.error('lc cannot tell which Light Code window this is. Run it from a pane inside the app.')
  process.exit(1)
}

const conn = net.connect(SOCKET)
let buf = ''
conn.on('connect', () => conn.write(JSON.stringify(parsed.req) + '\\n'))
conn.setEncoding('utf8')
conn.on('data', (d) => {
  buf += d
})
conn.on('error', () => {
  console.error('Light Code is not listening. Is the app running with the agent CLI switched on?')
  process.exit(1)
})
conn.on('close', () => {
  let res
  try {
    res = JSON.parse(buf.trim())
  } catch (_) {
    console.error('The app sent something unreadable.')
    process.exit(1)
  }
  if (!res.ok) {
    console.error(res.error || 'Refused.')
    process.exit(1)
  }
  if (res.protocol !== ${LC_PROTOCOL}) {
    console.error('This lc is version ${LC_PROTOCOL}; the app speaks ' + res.protocol + '. Restart the app.')
    process.exit(1)
  }
  console.log(parsed.json ? JSON.stringify(res) : render(res))
})
`
}

/** Write the client where the shell function expects it. Null if it could not. */
export function installLcClient(): string | null {
  try {
    mkdirSync(lcAssetDir(), { recursive: true })
    const path = lcScriptPath()
    const body = lcClientScript()
    let current: string | null = null
    try {
      current = readFileSync(path, 'utf8')
    } catch {
      // first launch, or somebody deleted it
    }
    // Every running instance shares this path, so a second launch truncating and
    // rewriting it could hand half a file to a pane running `lc` at that moment.
    // Nothing in the script varies between instances any more, so an identical
    // file is left exactly where it is.
    if (current !== body) writeFileSync(path, body, 'utf8')
    return path
  } catch {
    return null
  }
}
