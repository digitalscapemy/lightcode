/**
 * Live plan limits per Claude account, captured from Claude Code's status line.
 * See shared/planLimits.ts for why it is done this way.
 *
 * The status line is Light Code's only while the pane was started by Light
 * Code (it rides in the same `claude --settings` file as the hooks). It must
 * never cost the person their own status line, so the script looks it up the
 * way Claude Code would have (project local, project, then the account's
 * settings), runs it with the same input, and prints its output byte for byte.
 * Any failure of ours is swallowed: the worst case is a missing number, never
 * a broken status line.
 */

/** Shared by every running instance: the files are per account, not per window. */
export function limitsDir(): string {
  return join(app.getPath('userData'), 'plan-limits')
}

/**
 * Windows. PowerShell is the one shell every Windows has; stdin and stdout are
 * handled as raw UTF-8 bytes because PowerShell 5.1's own text pipes would
 * mangle anything outside ASCII (paths, the symbols status lines like to use).
 *
 * The person's command runs in Git Bash when there is one, as Claude Code on
 * Windows runs shell commands (it needs Git for Windows), else in cmd.
 */
export function windowsStatusLineScript(dir: string): string {
  return [
    '# Generated by Light Code. Saves Claude Code plan limits, then runs your own status line.',
    '$ErrorActionPreference = "SilentlyContinue"',
    '$utf8 = New-Object System.Text.UTF8Encoding($false)',
    '$reader = New-Object System.IO.StreamReader([Console]::OpenStandardInput(), $utf8)',
    '$raw = $reader.ReadToEnd()',
    '$cfg = if ($env:CLAUDE_CONFIG_DIR) { $env:CLAUDE_CONFIG_DIR } else { Join-Path $env:USERPROFILE ".claude" }',
    '$key = ($cfg.TrimEnd("\\", "/").ToLowerInvariant() -replace "[^a-z0-9]", "_")',
    'try {',
    '  if ($raw -match \'"rate_limits"\') {',
    `    $dir = ${psSingleQuote(dir)}`,
    '    $tmp = Join-Path $dir ($key + "." + $PID + ".tmp")',
    '    [System.IO.File]::WriteAllText($tmp, $raw, $utf8)',
    '    Move-Item -LiteralPath $tmp -Destination (Join-Path $dir ($key + ".json")) -Force',
    '  }',
    '} catch { }',
    '$cmd = $null',
    'foreach ($f in @(".claude\\settings.local.json", ".claude\\settings.json", (Join-Path $cfg "settings.json"))) {',
    '  if (-not (Test-Path -LiteralPath $f)) { continue }',
    '  try {',
    '    $j = [System.IO.File]::ReadAllText((Resolve-Path -LiteralPath $f).Path, $utf8) | ConvertFrom-Json',
    '    if ($j.statusLine -and $j.statusLine.command) { $cmd = [string]$j.statusLine.command; break }',
    '  } catch { }',
    '}',
    'if (-not $cmd) { exit 0 }',
    '$bash = $env:CLAUDE_CODE_GIT_BASH_PATH',
    'if (-not ($bash -and (Test-Path -LiteralPath $bash))) {',
    '  $bash = $null',
    '  $git = Get-Command git.exe -ErrorAction SilentlyContinue | Select-Object -First 1',
    '  if ($git) {',
    '    $root = Split-Path (Split-Path $git.Source)',
    '    foreach ($c in @((Join-Path $root "bin\\bash.exe"), (Join-Path $root "usr\\bin\\bash.exe"))) { if (Test-Path -LiteralPath $c) { $bash = $c; break } }',
    '  }',
    '  if (-not $bash) { $c = Join-Path $env:ProgramFiles "Git\\bin\\bash.exe"; if (Test-Path -LiteralPath $c) { $bash = $c } }',
    '}',
    '$psi = New-Object System.Diagnostics.ProcessStartInfo',
    'if ($bash) {',
    '  $psi.FileName = $bash',
    // Quoted for CreateProcess: backslashes before a quote, and at the end, double.
    '  $arg = ($cmd -replace \'(\\\\*)"\', \'$1$1\\"\') -replace \'(\\\\+)$\', \'$1$1\'',
    '  $psi.Arguments = \'-c "\' + $arg + \'"\'',
    '} else {',
    '  $psi.FileName = $env:ComSpec',
    '  $psi.Arguments = \'/d /s /c "\' + $cmd + \'"\'',
    '}',
    '$psi.UseShellExecute = $false',
    '$psi.RedirectStandardInput = $true',
    '$psi.RedirectStandardOutput = $true',
    '$psi.CreateNoWindow = $true',
    '$psi.WorkingDirectory = (Get-Location).Path',
    'try {',
    '  $p = [System.Diagnostics.Process]::Start($psi)',
    '  $inBytes = $utf8.GetBytes($raw)',
    '  $p.StandardInput.BaseStream.Write($inBytes, 0, $inBytes.Length)',
    '  $p.StandardInput.Close()',
    '  $out = New-Object System.IO.MemoryStream',
    '  $p.StandardOutput.BaseStream.CopyTo($out)',
    '  [void]$p.WaitForExit(10000)',
    '  $o = [Console]::OpenStandardOutput()',
    '  $bytes = $out.ToArray()',
    '  $o.Write($bytes, 0, $bytes.Length)',
    '  $o.Flush()',
    '} catch { }',
    'exit 0',
    ''
  ].join('\r\n')
}

/**
 * macOS (and other POSIX). No JSON parser is a given in sh, so the person's
 * status line is looked up with plutil (on every Mac), then python3.
 */
export function posixStatusLineScript(dir: string): string {
  const q = (s: string): string => `'${s.replace(/'/g, "'\\''")}'`
  return [
    '#!/bin/sh',
    '# Generated by Light Code. Saves Claude Code plan limits, then runs your own status line.',
    'input=$(cat)',
    'cfg="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"',
    "key=$(printf '%s' \"$cfg\" | sed 's#[/\\\\]*$##' | tr 'A-Z' 'a-z' | tr -c 'a-z0-9' '_')",
    `dir=${q(dir)}`,
    'case "$input" in',
    '  *\\"rate_limits\\"*)',
    '    tmp="$dir/$key.$$.tmp"',
    "    printf '%s' \"$input\" > \"$tmp\" 2>/dev/null && mv -f \"$tmp\" \"$dir/$key.json\" 2>/dev/null",
    '    ;;',
    'esac',
    'cmd=""',
    'for f in .claude/settings.local.json .claude/settings.json "$cfg/settings.json"; do',
    '  [ -f "$f" ] || continue',
    '  if command -v plutil >/dev/null 2>&1; then',
    '    c=$(plutil -extract statusLine.command raw -o - "$f" 2>/dev/null)',
    '  elif command -v python3 >/dev/null 2>&1; then',
    "    c=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get(\"statusLine\",{}).get(\"command\",\"\"))' \"$f\" 2>/dev/null)",
    '  else',
    '    c=""',
    '  fi',
    '  if [ -n "$c" ]; then cmd=$c; break; fi',
    'done',
    '[ -n "$cmd" ] || exit 0',
    "printf '%s' \"$input\" | ${SHELL:-/bin/sh} -c \"$cmd\"",
    'exit 0',
    ''
  ].join('\n')
}

/** The `statusLine` block for the `claude --settings` file. */
export function statusLineSetting(script: string): { type: 'command'; command: string } {
  if (process.platform === 'win32') {
    // Double quotes and forward slashes: read the same by Git Bash and cmd.
    const p = script.replace(/\\/g, '/')
    return { type: 'command', command: `powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${p}"` }
  }
  return { type: 'command', command: `/bin/sh '${script.replace(/'/g, "'\\''")}'` }
}

/**
 * Write the status line script into `hookDir`. Returns the setting to merge
 * into the hooks' settings file, or null to leave the status line alone.
 */
export function installStatusLine(hookDir: string): { type: 'command'; command: string } | null {
  try {
    const dir = limitsDir()
    mkdirSync(dir, { recursive: true })
    const win = process.platform === 'win32'
    const script = join(hookDir, win ? 'statusline.ps1' : 'statusline.sh')
    // A BOM so PowerShell 5.1 reads the script as UTF-8 whatever the folder name holds.
    const body = win ? '﻿' + windowsStatusLineScript(dir) : posixStatusLineScript(dir)
    if (!atomicWrite(script, body)) return null
    return statusLineSetting(script)
  } catch {
    return null
  }
}

/** Default plus every Claude account shortcut, de-duplicated by folder. */
function claudeAccounts(): { label: string; dir: string }[] {
  const list = [{ label: 'Default', dir: join(homedir(), '.claude') }]
  const seen = new Set([limitsKey(list[0]!.dir)])
  for (const a of loadShortcuts().accounts) {
    if (providerOf(a) !== 'claude') continue
    const dir = a.configDir.replace(/[\\/]+$/, '')
    const key = limitsKey(dir)
    if (!dir || seen.has(key)) continue
    seen.add(key)
    list.push({ label: a.name, dir })
  }
  return list
}

/** The latest limits seen for every Claude account. Cheap: one small file each. */
export async function planLimits(): Promise<AccountLimits[]> {
  const dir = limitsDir()
  return Promise.all(
    claudeAccounts().map(async (acc): Promise<AccountLimits> => {
      const id = limitsKey(acc.dir)
      const base: AccountLimits = { id, label: acc.label, configDir: acc.dir, fiveHour: null, sevenDay: null, updatedAt: null }
      const file = join(dir, `${id}.json`)
      try {
        const [text, st] = await Promise.all([readFile(file, 'utf8'), stat(file)])
        return { ...base, ...parseStatusLine(text.replace(/^﻿/, '')), updatedAt: st.mtimeMs }
      } catch {
        return base
      }
    })
  )
}
